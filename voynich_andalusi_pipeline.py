# 2. Función de evaluación angular y radial
def evaluar_anillo(puntos, centro):
  x0, y0 = centro
  angulos = [np.degrees(np.arctan2(y - y0, x - x0)) % 360 for x, y in puntos]
  angulos = np.sort(angulos)
  deltas = np.diff(angulos, append=angulos[0] + 360)
  teorico = 360.0 / len(puntos)
  rmse = np.sqrt(np.mean((deltas - teorico) ** 2))
  radios = [np.sqrt((x - x0) ** 2 + (y - y0) ** 2) for x, y in puntos]
  return deltas, teorico, rmse, np.mean(radios), np.std(radios)


