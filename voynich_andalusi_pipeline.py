import numpy as np


def analizar_geometria_rueda(puntos_radios, centroide):
    """Calcula las aperturas angulares y el RMSE frente a la division teorica."""
    x0, y0 = centroide
    angulos = []

    for x, y in puntos_radios:
        # Calculo del azimut polar
        theta = np.degrees(np.arctan2(y - y0, x - x0)) % 360
        angulos.append(theta)

    angulos = np.sort(angulos)
    deltas = np.diff(angulos, append=angulos[0] + 360)

    # Division uniforme esperada
    n_sectores = len(deltas)
    delta_teorico = 360.0 / n_sectores

    rmse = np.sqrt(np.mean((deltas - delta_teorico) ** 2))
    sigma = np.std(deltas)

    return deltas, rmse, sigma, delta_teorico

